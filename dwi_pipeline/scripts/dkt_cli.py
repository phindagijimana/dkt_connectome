def _subject_ids(root: Path) -> list[str]:
    ids: set[str] = set()
    markers = root / ".snakemake_markers"
    if markers.is_dir():
        for p in markers.iterdir():
            if p.is_dir() and p.name.startswith("sub-"):
                ids.add(p.name.removeprefix("sub-"))
    for subdir in ("connectomes", "freesurfer", "qc", "qsiprep_single_run_output"):
        base = root / subdir
        if not base.is_dir():
            continue
        for p in base.iterdir():
            if p.name.startswith("sub-"):
                ids.add(p.name.removeprefix("sub-").split("_")[0].split(".")[0])
    logs = root / "logs"
    if logs.is_dir():
        for p in logs.glob("sub-*.log"):
            # sub-001_qsiprep.log
            name = p.name.removeprefix("sub-")
            ids.add(name.split("_")[0])
    return sorted(ids)


def _stage_state(root: Path, subject: str) -> dict[str, str]:
    """Return done|missing|running per stage (short vocabulary)."""
    sub = f"sub-{subject}"
    markers = root / ".snakemake_markers" / sub
    states: dict[str, str] = {}

    def log_running(stage_key: str) -> bool:
        log = root / "logs" / f"{sub}_{stage_key}.log"
        if not log.is_file():
            return False
        # Recent activity without a marker ≈ still running / crashed mid-way.
        age = datetime.now(timezone.utc).timestamp() - log.stat().st_mtime
        return age < 6 * 3600  # 6h

    qsiprep_ok = (markers / "qsiprep.done").is_file()
    states["qsiprep"] = "done" if qsiprep_ok else ("running" if log_running("qsiprep") else "missing")

    fs = root / "freesurfer" / sub / "mri" / "aparc+aseg.mgz"
    fs_ok = fs.is_file() or (fs.is_symlink() and fs.exists())
    states["recon"] = "done" if fs_ok else ("running" if log_running("recon") else "missing")

    qsirecon_ok = (markers / "qsirecon.done").is_file()
    states["qsirecon"] = "done" if qsirecon_ok else ("running" if log_running("qsirecon") else "missing")

    conn = root / "connectomes" / sub / "dkt_connectome.csv"
    conn_ok = conn.is_file() or (conn.is_symlink() and conn.exists())
    states["connectome"] = (
        "done" if conn_ok else ("running" if log_running("connectome") else "missing")
    )

    qc = root / "qc" / sub / "subject_qc.html"
    qc_ok = qc.is_file() or (qc.is_symlink() and qc.exists())
    states["qc"] = "done" if qc_ok else "missing"
    return states


def _mark(state: str) -> str:
    return {"done": "OK", "running": "..", "missing": "--"}.get(state, state)


def cmd_status(args: argparse.Namespace) -> int:
    root = Path(args.results_root).expanduser().resolve()
    if not root.is_dir():
        print(f"ERROR [status]: results root not found: {root}", file=sys.stderr)
        print(
            _next_steps_block(
                [
                    "Pass --results-root /path/to/OUT (or export RESULTS_ROOT)",
                    "After a run: ./dkt status --results-root OUT",
                ]
            ),
            file=sys.stderr,
        )
        return 2

    subjects = _subject_ids(root)
    if args.subject:
        want = args.subject.removeprefix("sub-")
        subjects = [s for s in subjects if s == want]
        if not subjects:
            subjects = [want]

    if not subjects:
        print(f"[status] no subjects found under {root}")
        print(
            _next_steps_block(
                [
                    f"./dkt run BIDS {root} participant --participant-label ID --profile ideas",
                    f"./dkt log --results-root {root} --list",
                ]
            )
        )
        return 0

    # Compact header
    headers = ["subject"] + [label for _, label in STAGES]
    widths = [max(8, len(h)) for h in headers]
    rows: list[list[str]] = []
    summary = {"done": 0, "partial": 0, "empty": 0}

    for sid in subjects:
        states = _stage_state(root, sid)
        cells = [f"sub-{sid}"] + [_mark(states[k]) for k, _ in STAGES]
        rows.append(cells)
        for i, h in enumerate(headers):
            widths[i] = max(widths[i], len(cells[i]))
        vals = list(states.values())
        if all(v == "done" for v in vals):
            summary["done"] += 1
        elif all(v == "missing" for v in vals):
            summary["empty"] += 1
        else:
            summary["partial"] += 1

    def fmt(row: list[str]) -> str:
        return "  ".join(c.ljust(w) for c, w in zip(row, widths))

    print(f"[status] {root}")
    print(fmt(headers))
    print(fmt(["-" * w for w in widths]))
    for row in rows:
        print(fmt(row))
    print(
        f"\n[status] {len(subjects)} subject(s): "
        f"{summary['done']} complete, {summary['partial']} in progress, {summary['empty']} not started"
    )
    print("  legend: OK=done  ..=recent log / likely running  --=not found")

    # Optional machine-readable snapshot (for scripts; quiet by default path)
    status_dir = root / "status"
    if args.write:
        status_dir.mkdir(parents=True, exist_ok=True)
        payload = {
            "generated": _utc_now(),
            "pipeline_version": _pipeline_version(),
            "results_root": str(root),
            "subjects": {
                sid: _stage_state(root, sid) for sid in subjects
            },
            "summary": summary,
        }
        out_json = status_dir / "summary.json"
        out_json.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
        print(f"[status] wrote {out_json}")

    # One clear next action (first unfinished stage for the first subject)
    if summary["partial"] or summary["empty"]:
        first = subjects[0]
        states = _stage_state(root, first)
        stage_mode = {
            "qsiprep": "qsiprep",
            "recon": "recon",
            "qsirecon": "qsirecon",
            "connectome": "connectome",
            "qc": "all",
        }
        nxt = f"./dkt check --outputs --subject {first} --results-root {root}"
        for key, _label in STAGES:
            if states[key] != "done":
                if states[key] == "running":
                    nxt = f"./dkt log --results-root {root} --subject {first} --stage {key}"
                else:
                    mode = stage_mode[key]
                    nxt = (
                        f"./dkt run BIDS {root} participant --participant-label {first} "
                        f"--mode {mode} --profile ideas"
                    )
                break
        print(_next_steps_block([nxt, f"./dkt log --results-root {root} --subject {first}"]))
    else:
        print(
            _next_steps_block(
                [
                    f"open {root}/qc/sub-<ID>/subject_qc.html",
                    f"./run BIDS {root} group   # cohort indexes + derivatives export",
                ]
            )
        )
    return 0


