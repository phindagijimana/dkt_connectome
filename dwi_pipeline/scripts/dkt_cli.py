def expand_profile(name: str) -> list[str]:
    key = name.strip().lower()
    if key not in PROFILES:
        valid = ", ".join(PROFILES)
        raise SystemExit(f"ERROR: unknown profile {name!r}. Valid: {valid}")
    return list(PROFILES[key]["flags"])


def cmd_profiles(_args: argparse.Namespace) -> int:
    print("Run profiles (pass to ./dkt run … --profile NAME):\n")
    for name, spec in PROFILES.items():
        flags = " ".join(spec["flags"]) or "(pipeline defaults)"
        print(f"  {name:8}  {spec['description']}")
        print(f"           flags: {flags}")
    print(
        _next_steps_block(
            [
                "./dkt run BIDS OUT participant --participant-label 001 --profile ideas",
                "./dkt profiles   # this list",
            ]
        )
    )
    return 0


