def cmd_provenance(args: argparse.Namespace) -> int:
    root = Path(args.results_root).expanduser().resolve() if args.results_root else None
    print(f"[provenance] pipeline {_pipeline_version()}")
    if RELEASE_MANIFEST.is_file():
        try:
            man = json.loads(RELEASE_MANIFEST.read_text(encoding="utf-8"))
            print(f"[provenance] release_manifest pipeline_version={man.get('pipeline_version')}")
            steps = man.get("steps") or {}
            for key in ("qsiprep", "qsirecon", "freesurfer", "fastsurfer", "connectome"):
                spec = steps.get(key) or {}
                uri = spec.get("uri")
                if uri:
                    sha = spec.get("sha256")
                    dig = (sha[:12] + "…") if isinstance(sha, str) and sha else "unpinned"
                    print(f"  {key:12} {uri}  ({dig})")
        except (OSError, ValueError, TypeError, json.JSONDecodeError) as exc:
            print(f"[provenance] could not read release_manifest: {exc}", file=sys.stderr)

    desc = (root / "dataset_description.json") if root else None
    if desc and desc.is_file():
        try:
            data = json.loads(desc.read_text(encoding="utf-8"))
            print(f"[provenance] dataset_description: {desc}")
            for k in ("Name", "PipelineVersion", "GeneratedBy", "SourceDatasets"):
                if k in data:
                    print(f"  {k}: {data[k]}")
        except (OSError, ValueError, TypeError, json.JSONDecodeError):
            pass
    elif root:
        print(f"[provenance] no dataset_description.json yet under {root}")

    if args.subject and root:
        sid = args.subject.removeprefix("sub-")
        states = _stage_state(root, sid)
        print(f"[provenance] sub-{sid} stages: " + ", ".join(f"{k}={v}" for k, v in states.items()))

    print(
        _next_steps_block(
            [
                "./dkt check --strict   # verify container digests when recorded",
                "Cite: https://dkt-connectome.readthedocs.io/en/latest/citation.html",
            ]
        )
    )
    return 0


