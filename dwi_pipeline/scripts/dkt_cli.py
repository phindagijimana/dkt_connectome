def cmd_bids_exec_spec(_args: argparse.Namespace) -> int:
    json.dump(boutiques_descriptor(), sys.stdout, indent=2)
    sys.stdout.write("\n")
    return 0


def cmd_expand_profile(args: argparse.Namespace) -> int:
    """Print profile flags as shell words (used by ./run)."""
    flags = expand_profile(args.name)
    print(" ".join(flags))
    return 0


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(description=__doc__)
    sub = p.add_subparsers(dest="command", required=True)

    p_init = sub.add_parser("init", help="Write config.local.yaml and show next steps")
    p_init.add_argument("--license", default=None, help="Path to FreeSurfer license.txt")
    p_init.add_argument("--bids", default=None, help="Optional BIDS dataset root")
    p_init.add_argument("--out", default=None, help="Optional results / output root")
    p_init.add_argument("--cache", default=None, help="Container cache directory")
    p_init.add_argument("--force", action="store_true", help="Overwrite config.local.yaml")
    p_init.add_argument(
        "--yes",
        action="store_true",
        help="Non-interactive; still requires --license unless FS_LICENSE is set",
    )
    p_init.set_defaults(func=cmd_init)

    p_st = sub.add_parser("status", help="Subject × stage table for a results root")
    p_st.add_argument(
        "--results-root",
        default=os.environ.get("RESULTS_ROOT"),
        help="Results root (default: $RESULTS_ROOT)",
    )
    p_st.add_argument("--subject", default=None, help="Limit to one subject")
    p_st.add_argument(
        "--write",
        action="store_true",
        help="Also write status/summary.json under the results root",
    )
    p_st.set_defaults(func=cmd_status)

    p_pr = sub.add_parser("profiles", help="List named run profiles")
    p_pr.set_defaults(func=cmd_profiles)

    p_exp = sub.add_parser("expand-profile", help=argparse.SUPPRESS)
    p_exp.add_argument("name")
    p_exp.set_defaults(func=cmd_expand_profile)

    p_prov = sub.add_parser("provenance", help="Short provenance summary")
    p_prov.add_argument("--results-root", default=os.environ.get("RESULTS_ROOT"))
    p_prov.add_argument("--subject", default=None)
    p_prov.set_defaults(func=cmd_provenance)

    p_bes = sub.add_parser(
        "bids-exec-spec",
        help="Print Boutiques descriptor (BIDS execution-spec)",
    )
    p_bes.set_defaults(func=cmd_bids_exec_spec)

    return p


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    return int(args.func(args))


if __name__ == "__main__":
    raise SystemExit(main())
