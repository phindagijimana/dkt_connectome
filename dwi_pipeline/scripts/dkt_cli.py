def cmd_init(args: argparse.Namespace) -> int:
    """Write a minimal config.local.yaml and print a short getting-started path."""
    license_path = Path(args.license).expanduser() if args.license else None
    cache = Path(
        args.cache
        or os.environ.get("DKT_CONTAINER_CACHE")
        or (Path.home() / ".cache" / "dkt-connectome" / "containers")
    ).expanduser()
    bids = Path(args.bids).expanduser() if args.bids else None
    out = Path(args.out).expanduser() if args.out else None

    if license_path is None and not args.yes:
        env_lic = os.environ.get("FS_LICENSE")
        if env_lic:
            license_path = Path(env_lic).expanduser()

    errors: list[str] = []
    if license_path is None:
        errors.append("Pass --license /path/to/license.txt (or export FS_LICENSE)")
    elif not license_path.is_file():
        errors.append(f"FreeSurfer license not found: {license_path}")
    if bids is not None and not (bids / "dataset_description.json").is_file():
        errors.append(f"BIDS root missing dataset_description.json: {bids}")
    if errors:
        for e in errors:
            print(f"ERROR [init]: {e}", file=sys.stderr)
        print(
            _next_steps_block(
                [
                    "Register for a FreeSurfer license: https://surfer.nmr.mgh.harvard.edu/registration.html",
                    "./dkt init --license ~/freesurfer/license.txt [--bids BIDS] [--out OUT]",
                ]
            ),
            file=sys.stderr,
        )
        return 2

    assert license_path is not None
    cache.mkdir(parents=True, exist_ok=True)
    if out is not None:
        out.mkdir(parents=True, exist_ok=True)

    # Prefer paths already discovered by install; otherwise leave containers to install.
    lines = [
        "# Generated by ./dkt init — edit paths as needed (gitignored).",
        f"# pipeline_version: {_pipeline_version()}",
        f"# generated: {_utc_now()}",
        "",
        f"fs_license: {license_path.resolve()}",
        "",
    ]
    if bids is not None:
        lines.append(f"bids_dir: {bids.resolve()}")
    if out is not None:
        lines.append(f"results_root: {out.resolve()}")
    lines.append("")
    lines.append("# After ./dkt install, containers: paths are filled automatically.")
    lines.append("# Or set CONTAINER_* env vars — ./dkt check finds either.")
    lines.append("")

    if LOCAL_CONFIG.is_file() and not args.force:
        print(f"[init] keep existing {LOCAL_CONFIG} (pass --force to overwrite)")
    else:
        LOCAL_CONFIG.parent.mkdir(parents=True, exist_ok=True)
        LOCAL_CONFIG.write_text("\n".join(lines) + "\n", encoding="utf-8")
        print(f"[init] wrote {LOCAL_CONFIG}")

    env_hint = f"export FS_LICENSE={license_path.resolve()}"
    print(f"[init] cache: {cache}")
    print(f"[init] {env_hint}")
    print(
        _next_steps_block(
            [
                env_hint,
                f"export DKT_CONTAINER_CACHE={cache}",
                "./dkt install          # or: ./dkt install qsirecon",
                "./dkt check",
                (
                    f"./dkt run {bids or 'BIDS'} {out or 'OUT'} participant "
                    "--participant-label ID --profile ideas"
                    if bids or out
                    else "./dkt run BIDS OUT participant --participant-label ID --profile ideas"
                ),
            ]
        )
    )
    return 0


