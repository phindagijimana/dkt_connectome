#!/usr/bin/env python3
"""Human-facing helpers for ./dkt (init, status, profiles, provenance, Boutiques).

Keep the surface small: clear next steps, no noisy dashboards by default.
The BIDS App contract remains ./run <bids> <out> <level>.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from datetime import datetime, timezone
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
DWI = SCRIPT_DIR.parent
APP_JSON = DWI / "app.json"
CONFIG_DIR = DWI / "workflow" / "config"
LOCAL_CONFIG = CONFIG_DIR / "config.local.yaml"
RELEASE_MANIFEST = DWI / "release_manifest.json"

# Ordered stages shown in status (keep short — clarity over completeness).
STAGES = (
    ("qsiprep", "QSIPrep"),
    ("recon", "Recon"),
    ("qsirecon", "QSIRecon"),
    ("connectome", "Connectome"),
    ("qc", "QC"),
)

# Named flag packs — not full config dumps.
PROFILES: dict[str, dict] = {
    "minimal": {
        "description": "Core pipeline defaults (no lesion extras)",
        "flags": [],
    },
    "ideas": {
        "description": "IDEAS-style: FastSurfer + SyN SDC",
        "flags": ["--fastsurfer", "--syn"],
    },
    "glioma": {
        "description": "Lesion path: FastSurfer + inpaint + lesion-aware ACT",
        "flags": [
            "--fastsurfer",
            "--syn",
            "--inpaint",
            "--act-mode",
            "lesion-aware",
        ],
    },
}


def _utc_now() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def _pipeline_version() -> str:
    try:
        return str(json.loads(APP_JSON.read_text(encoding="utf-8")).get("PipelineVersion", "unknown"))
    except (OSError, ValueError, TypeError, json.JSONDecodeError):
        return "unknown"


def _next_steps_block(lines: list[str]) -> str:
    body = "\n".join(f"  {i}. {line}" for i, line in enumerate(lines, 1))
    return f"\nNext:\n{body}\n"


